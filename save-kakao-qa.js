async function saveToSheet() {
    console.log('📊 Google Sheets에 저장 시작...');
    console.log('데이터 개수:', qnaData.length - 1, '개 (헤더 제외)');

    try {
        // 로컬 Vercel dev 서버의 collect API 호출
        const response = await fetch('http://localhost:3002/api/collect', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                action: 'appendToSheet',
                sheetName: '카톡 Q&A',
                values: qnaData
            })
        });

        const text = await response.text();
        console.log('API 응답:', text);

        if (response.ok) {
            console.log('✅ 저장 성공!');
        } else {
            console.log('❌ 저장 실패, 상태:', response.status);
        }
    } catch (error) {
        console.error('❌ 오류:', error.message);
    }
}

saveToSheet();
