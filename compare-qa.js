let output = '# 새 Q&A vs 기존 Q&A 비교\n\n';

newQAs.forEach(newQ => {
    // 키워드로 유사 Q&A 찾기
    const matches = items.filter(item => {
        const text = (item.question + ' ' + item.answer).toLowerCase();
        return newQ.keywords.some(kw => text.includes(kw.toLowerCase()));
    }).slice(0, 3); // 상위 3개만

    output += `---\n\n`;
    output += `## ${newQ.id}. 새 Q&A\n\n`;
    output += `**Q:** ${newQ.question}\n\n`;
    output += `**A:** ${newQ.answer}\n\n`;

    if (matches.length === 0) {
        output += `### ✅ 기존 유사 Q&A: 없음 (신규 추가 권장)\n\n`;
    } else {
        output += `### ⚠️ 기존 유사 Q&A (${matches.length}개)\n\n`;
        matches.forEach((m, idx) => {
            output += `**[기존 ${idx + 1}] Q:** ${m.question}\n\n`;
            output += `**A:** ${m.answer.substring(0, 200)}...\n\n`;
        });
    }
});

fs.writeFileSync('qa-comparison.md', output, 'utf8');
console.log('비교 파일 생성 완료: qa-comparison.md');
